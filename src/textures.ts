function makeBackground(scene: Phaser.Scene, id: ThemeId, t: Theme): void {
  const { far, near, detail } = t.bg;
  make(scene, `bg_${id}`, 128, 240, (g) => {
    const rnd = new Phaser.Math.RandomDataGenerator([id]);
    switch (t.bg.style) {
      case 'skyline': {
        for (let i = 0; i < 40; i++) rect(g, rnd.pick([0x3a3f66, 0x5a5f8a, detail]), rnd.between(0, 127), rnd.between(0, 150), 1, 1);
        [70, 40, 90, 55, 110, 65, 45, 85].forEach((hgt, i) => {
          rect(g, far, i * 16, 240 - hgt, 15, hgt);
          for (let y = 240 - hgt + 6; y < 236; y += 10) rect(g, near, i * 16 + 4, y, 2, 3);
        });
        break;
      }
      case 'trees': {
        // Trunks with hanging leaf clumps.
        for (const x of [6, 40, 70, 104]) {
          rect(g, far, x, 0, 10, 240);
          rect(g, near, x + 2, 0, 2, 240);
        }
        for (let i = 0; i < 26; i++) {
          const x = rnd.between(-8, 120);
          const y = rnd.between(0, 200);
          rect(g, near, x, y, rnd.between(14, 26), rnd.between(6, 12));
          rect(g, detail, x + 3, y + 2, 6, 2);
        }
        break;
      }
      case 'mountains': {
        for (let i = 0; i < 30; i++) rect(g, detail, rnd.between(0, 127), rnd.between(0, 200), 1, 1);
        tri(g, far, -20, 240, 40, 110, 100, 240);
        tri(g, near, 50, 240, 100, 140, 160, 240);
        tri(g, detail, 30, 128, 40, 110, 50, 128);
        tri(g, detail, 92, 154, 100, 140, 108, 154);
        break;
      }
      case 'clouds': {
        const puff = (x: number, y: number, w: number, color: number) => {
          rect(g, color, x, y + 4, w, 8);
          rect(g, color, x + 4, y, w / 2, 6);
        };
        puff(4, 40, 40, far);
        puff(70, 90, 48, far);
        puff(20, 150, 56, far);
        puff(84, 190, 40, near);
        puff(-10, 210, 50, near);
        puff(60, 220, 60, near);
        break;
      }
      case 'circuit': {
        // Circuit traces and glowing nodes.
        for (let i = 0; i < 10; i++) {
          const x = rnd.between(0, 120);
          const y = rnd.between(0, 230);
          rect(g, near, x, y, rnd.between(10, 40), 2);
          rect(g, near, x, y, 2, rnd.between(10, 40));
          rect(g, detail, x - 1, y - 1, 4, 4);
        }
        for (let y = 0; y < 240; y += 32) rect(g, far, 0, y, 128, 1);
        break;
      }
      case 'volcano': {
        tri(g, far, -10, 240, 64, 90, 140, 240);
        rect(g, detail, 58, 90, 12, 4);
        tri(g, near, 60, 240, 110, 150, 160, 240);
        for (let i = 0; i < 24; i++) rect(g, rnd.pick([detail, 0xffc040]), rnd.between(0, 127), rnd.between(0, 200), 1, 1);
        break;
      }
      case 'scrapheap': {
        // Piles of junk and girders.
        for (let i = 0; i < 18; i++) {
          const w = rnd.between(10, 30);
          const h = rnd.between(6, 18);
          rect(g, rnd.pick([far, near]), rnd.between(-10, 120), rnd.between(130, 240 - h), w, h);
        }
        for (const x of [20, 84]) {
          rect(g, near, x, 40, 4, 200);
          for (let y = 50; y < 240; y += 16) rect(g, detail, x - 4, y, 12, 2);
        }
        break;
      }
      case 'reef': {
        // Light shafts, coral and bubbles.
        for (const x of [10, 60, 100]) rect(g, near, x, 0, 8, 240);
        for (let i = 0; i < 12; i++) {
          const x = rnd.between(0, 120);
          const h = rnd.between(16, 50);
          rect(g, rnd.pick([0x6a3a5a, 0x3a6a5a, 0x7a5a3a]), x, 240 - h, rnd.between(4, 8), h);
        }
        for (let i = 0; i < 20; i++) rect(g, detail, rnd.between(0, 127), rnd.between(0, 220), 2, 2);
        break;
      }
      case 'city': {
        // White buildings with green and orange awnings and windows.
        [120, 90, 140, 100].forEach((hgt, i) => {
          const x = i * 32;
          rect(g, far, x, 240 - hgt, 30, hgt);
          rect(g, 0xd8d4cc, x + 28, 240 - hgt, 2, hgt);
          rect(g, i % 2 ? near : detail, x, 240 - hgt + 14, 30, 4);
          for (let y = 240 - hgt + 24; y < 228; y += 16) {
            rect(g, 0x9ac8e0, x + 5, y, 7, 8);
            rect(g, 0x9ac8e0, x + 18, y, 7, 8);
          }
        });
        break;
      }
      case 'fortress': {
        // Towers with red windows.
        [120, 80, 150, 100, 130].forEach((hgt, i) => {
          const x = i * 26 - 4;
          rect(g, far, x, 240 - hgt, 22, hgt);
          rect(g, near, x + 2, 240 - hgt - 6, 4, 6);
          rect(g, near, x + 16, 240 - hgt - 6, 4, 6);
          for (let y = 240 - hgt + 10; y < 230; y += 18) rect(g, detail, x + 9, y, 4, 5);
        });
        break;
      }
    }
  });
}

